#!/usr/bin/env python3
"""Build The Heart key drawings from the tracing + keys.py.

  python3 trace_master.py   # only if trace.json needs regenerating (reads the master)
  python3 build.py          # writes ../storyboard/*.png and ../keys.js

Outputs are transparent RGBA PNGs at master resolution. They are STUDIES.
"""
import json
from pathlib import Path
import numpy as np
from PIL import Image
import kc, ink, keys

OUT = kc.HERE.parent / "storyboard"

def save(img, path):
    # keep files small: grain is subtle, 96 colours + alpha is visually lossless here
    q = img.quantize(colors=96, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    q.save(path, optimize=True)

def main():
    OUT.mkdir(exist_ok=True)
    meta = []
    for i, k in enumerate(keys.KEYS):
        groups, pal = kc.draw_key(k)
        img = ink.render(groups, pal, seed=11+i)
        save(img, OUT / f"{k['id']}.png")
        if i == 0:
            a = np.asarray(img)[..., 3]
            sil = np.zeros(a.shape+(4,), np.uint8); sil[..., :3] = pal["ink"]; sil[..., 3] = a
            save(Image.fromarray(sil, "RGBA"), OUT / "silhouette-home.png")
            ys, xs = np.nonzero(a > 128)
            bbox = [int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max())]
        meta.append({x: k[x] for x in ("id", "title", "beat", "note", "hold")} |
                    {"redrawn": sorted((k.get("face") or {}).keys()),
                     "warps": [o[0] for o in k.get("ops", [])], "heart": k.get("heart", [])})
        print("drew", k["id"])
    g, pal = kc.load()
    radii = np.array([p[2] for s in g["strokes"] for p in s])
    info = dict(size=list(kc.SIZE), fps=12, palette={n: pal[n] for n in ("paper", "ink", "red", "skin")},
                figure_bbox=bbox, line_width_px=[round(float(np.percentile(radii, q))*2, 1) for q in (10, 50, 90)],
                landmarks=dict(box=kc.BOX, neck=kc.NECK, knot=kc.KNOT, shoulder=kc.SHOULDER),
                status="study — awaiting creator approval", keys=meta)
    (kc.HERE.parent / "keys.js").write_text("// generated by project/build.py — do not edit\nwindow.KC = " +
                                            json.dumps(info, indent=1) + ";\n")

if __name__ == "__main__":
    main()
