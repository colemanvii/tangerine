#!/usr/bin/env python3
"""Build The Heart: key drawings, the rough motion-test frames, and exports.

  python3 trace_master.py   # only if trace.json needs regenerating (reads the master)
  python3 build.py          # storyboard/, frames/, timing.json, keys.js, ../../exports/

Everything written here is an exploratory STUDY, not approved character art.
"""
import json, subprocess, shutil
from pathlib import Path
import numpy as np
from PIL import Image
import kc, ink, motion

SHOT = kc.HERE.parent
STORY, FRAMES = SHOT / "storyboard", SHOT / "frames"
EXPORTS = SHOT.parents[1] / "exports"
VERSION = "v01"

def save(img, path):
    # grain is subtle: 96 colours + alpha is visually lossless and keeps the repo small
    img.quantize(colors=96, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(path, optimize=True)

def drawing(f):
    """Frame f of the loop. Frame 0 is the pure tracing of the master pose."""
    groups, pal = kc.draw_key(motion.pose(f) if f % motion.N else {})
    return ink.render(groups, pal, seed=100 + f), pal      # new seed each drawing: the ink and grain boil

def paper(pal, size):
    n = ink._noise(size, 7, ((2, .5), (6, .3), (24, .2)))
    col = np.clip(np.asarray(pal["paper"], float)[None, None, :]*(1 + 0.035*n[..., None]), 0, 255)
    return Image.fromarray(np.dstack([col, np.full(n.shape, 255.0)]).astype(np.uint8), "RGBA")

def main():
    for d in (STORY, FRAMES, EXPORTS): d.mkdir(exist_ok=True)
    frames = []
    for f in range(motion.N):
        img, pal = drawing(f)
        save(img, FRAMES / f"frame-{f+1:04d}.png"); frames.append(img)
        print("frame", f+1)
    for k in motion.KEYS:
        shutil.copyfile(FRAMES / f"frame-{k['frame']+1:04d}.png", STORY / f"{k['id']}.png")
    a = np.asarray(frames[0])[..., 3]
    sil = np.zeros(a.shape+(4,), np.uint8); sil[..., :3] = pal["ink"]; sil[..., 3] = a
    save(Image.fromarray(sil, "RGBA"), STORY / "silhouette-home.png")

    timing = dict(shot="001-the-heart", status="rough motion test — exploratory, not approved", fps=motion.FPS, loop=True,
                  frames=[dict(file=f"frames/frame-{f+1:04d}.png", duration_frames=1) for f in range(motion.N)],
                  technique="traced-and-adjusted drawings generated by project/build.py; squeeze heart and hand are new drawings")
    (SHOT / "timing.json").write_text(json.dumps(timing, indent=1))

    # exports: half size, transparent WebP + MP4 on procedural paper
    half = (kc.SIZE[0]//2, kc.SIZE[1]//2)
    small = [fr.resize(half, Image.LANCZOS) for fr in frames]
    name = f"lil-kc-the-heart-rough-{VERSION}"
    small[0].save(EXPORTS / f"{name}.webp", save_all=True, append_images=small[1:], duration=round(1000/motion.FPS),
                  loop=0, quality=82, method=4)
    bg = paper(pal, kc.SIZE); tmp = SHOT / "_mp4"; tmp.mkdir(exist_ok=True)
    for i in range(motion.N*2):                                 # two loops
        c = bg.copy(); c.alpha_composite(frames[i % motion.N]); c.convert("RGB").save(tmp / f"{i:04d}.png")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-framerate", str(motion.FPS), "-i", str(tmp / "%04d.png"),
                    "-vf", "scale=1152:768", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "20", str(EXPORTS / f"{name}.mp4")], check=True)
    shutil.rmtree(tmp)

    g, pal = kc.load()
    radii = np.array([p[2] for s in g["strokes"] for p in s])
    info = dict(size=list(kc.SIZE), fps=motion.FPS, frames=motion.N, palette={n: pal[n] for n in ("paper", "ink", "red", "skin")},
                line_width_px=[round(float(np.percentile(radii, q))*2, 1) for q in (10, 50, 90)],
                status="rough motion test — awaiting creator review", keys=motion.KEYS)
    (SHOT / "keys.js").write_text("// generated by project/build.py — do not edit\nwindow.KC = " + json.dumps(info, indent=1) + ";\n")

if __name__ == "__main__":
    main()
